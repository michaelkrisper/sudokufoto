#!/usr/bin/env python3
"""Trains the digit net on samples from tools/extract.mjs and writes js/model.js.

  tools/train.py TRAIN.bin [TRAIN2.bin ...] --val VAL.bin [--epochs 30]

Net: FEAT*FEAT inputs -> 128 ReLU -> 9 softmax (digits 1..9), plain numpy with
Adam. Weights are stored as int8 with one scale per output unit.
"""

import argparse
import base64
import json
import os

import numpy as np

FEAT = 24
HIDDEN = 128


def load(paths):
    raw = np.concatenate([np.fromfile(p, np.uint8) for p in paths])
    raw = raw.reshape(-1, 1 + FEAT * FEAT)
    return raw[:, 1:].astype(np.float32) / 255, raw[:, 0].astype(np.int64) - 1


def augment(x, rng):
    """Shift by a pixel, thicken or thin strokes a little."""
    img = x.reshape(-1, FEAT, FEAT)
    out = np.empty_like(img)
    for k in range(len(img)):
        a = img[k]
        dy, dx = rng.integers(-1, 2, 2)
        a = np.roll(np.roll(a, dy, 0), dx, 1)
        r = rng.random()
        if r < 0.2:
            p = np.pad(a, 1)
            a = np.max([p[1 + i:FEAT + 1 + i, 1 + j:FEAT + 1 + j] for i, j in [(0, 0), (0, 1), (1, 0)]], 0)
        elif r < 0.35:
            p = np.pad(a, 1)
            a = np.min([p[1 + i:FEAT + 1 + i, 1 + j:FEAT + 1 + j] for i, j in [(0, 0), (0, 1), (1, 0)]], 0)
        out[k] = a
    return out.reshape(len(x), -1)


def forward(p, x):
    h = np.maximum(0, x @ p["w1"].T + p["b1"])
    z = h @ p["w2"].T + p["b2"]
    z -= z.max(1, keepdims=True)
    e = np.exp(z)
    return h, e / e.sum(1, keepdims=True)


def quantise(w):
    scale = np.abs(w).max(1) / 127 + 1e-12
    q = np.clip(np.round(w / scale[:, None]), -127, 127).astype(np.int8)
    return q, scale


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("train", nargs="+")
    ap.add_argument("--val", required=True)
    ap.add_argument("--epochs", type=int, default=30)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "js", "model.js"))
    a = ap.parse_args()
    rng = np.random.default_rng(0)
    x, y = load(a.train)
    xv, yv = load([a.val])
    print(f"train {len(x)}  val {len(xv)}  per digit {np.bincount(y, minlength=9)}")
    n_in = FEAT * FEAT
    p = {
        "w1": rng.normal(0, np.sqrt(2 / n_in), (HIDDEN, n_in)).astype(np.float32),
        "b1": np.zeros(HIDDEN, np.float32),
        "w2": rng.normal(0, np.sqrt(2 / HIDDEN), (9, HIDDEN)).astype(np.float32),
        "b2": np.zeros(9, np.float32),
    }
    m = {k: np.zeros_like(v) for k, v in p.items()}
    v2 = {k: np.zeros_like(v) for k, v in p.items()}
    step, bs, lr0, wd = 0, 256, 2e-3, 1e-4
    for ep in range(a.epochs):
        lr = lr0 * 0.5 * (1 + np.cos(np.pi * ep / a.epochs))
        idx = rng.permutation(len(x))
        xa = augment(x[idx], rng)
        ya = y[idx]
        for s in range(0, len(xa), bs):
            xb, yb = xa[s:s + bs], ya[s:s + bs]
            h, pr = forward(p, xb)
            g = pr.copy()
            g[np.arange(len(yb)), yb] -= 1
            g /= len(yb)
            grads = {"w2": g.T @ h, "b2": g.sum(0)}
            gh = (g @ p["w2"]) * (h > 0)
            grads["w1"] = gh.T @ xb
            grads["b1"] = gh.sum(0)
            step += 1
            for k in p:
                gk = grads[k] + (wd * p[k] if k[0] == "w" else 0)
                m[k] = 0.9 * m[k] + 0.1 * gk
                v2[k] = 0.999 * v2[k] + 0.001 * gk * gk
                mh = m[k] / (1 - 0.9**step)
                vh = v2[k] / (1 - 0.999**step)
                p[k] -= lr * mh / (np.sqrt(vh) + 1e-8)
        _, pv = forward(p, xv)
        acc = (pv.argmax(1) == yv).mean()
        print(f"epoch {ep + 1:2d}  val acc {acc * 100:.3f}%  ({int((1 - acc) * len(yv))} wrong)")

    # check the quantised net, as the app will run it
    q1, s1 = quantise(p["w1"])
    q2, s2 = quantise(p["w2"])
    pq = {"w1": q1 * s1[:, None], "b1": p["b1"], "w2": q2 * s2[:, None], "b2": p["b2"]}
    _, pv = forward(pq, xv)
    pred = pv.argmax(1)
    print(f"quantised val acc {(pred == yv).mean() * 100:.3f}%")
    conf = np.zeros((9, 9), int)
    for t, q in zip(yv, pred):
        conf[t, q] += 1
    for t in range(9):
        errs = {q + 1: conf[t, q] for q in range(9) if q != t and conf[t, q]}
        if errs:
            print(f"  {t + 1} read as {errs}")

    def layer(q, s, b):
        return {"in": int(q.shape[1]), "out": int(q.shape[0]),
                "w": base64.b64encode(q.tobytes()).decode(),
                "scale": [float(f"{v:.6g}") for v in s], "b": [float(f"{v:.6g}") for v in b]}

    model = {"feat": FEAT, "layers": [layer(q1, s1, p["b1"]), layer(q2, s2, p["b2"])]}
    with open(a.out, "w") as f:
        f.write("// Generated by tools/train.py, do not edit.\n")
        f.write(f"export const MODEL = {json.dumps(model, separators=(',', ':'))};\n")
    print(f"wrote {a.out} ({os.path.getsize(a.out) // 1024} KB)")


if __name__ == "__main__":
    main()
